#!/usr/bin/env python3
"""Write API.md from the tools the server actually serves.

    python scripts/generate_api_reference.py          # rewrite API.md
    python scripts/generate_api_reference.py --check  # exit 1 if API.md is out of date

Every table in API.md is read from a live server: the names, arguments and
descriptions a client sees, and the output schema each tool declares. Nothing
in the file is typed by hand, so it cannot describe a surface that no longer
exists; a test runs `--check`.
"""

import asyncio
import json
import sys
import tempfile
from pathlib import Path
from typing import Any, Dict, List

from fastmcp import Client

from laravel_mcp_companion import __version__
from laravel_mcp_companion.server import create_mcp_server
from laravel_mcp_companion.tools import ERROR_MEANINGS, EXPERIMENTAL_TOOLS, REGISTRY

TARGET = Path(__file__).resolve().parents[1] / "API.md"

GROUPS = [
    ("Documentation", [
        "search_laravel_docs", "read_laravel_doc_section", "read_laravel_doc_content", "list_laravel_docs",
        "laravel_docs_info", "compare_laravel_versions", "update_laravel_docs",
    ]),
    ("Package catalog and services", ["get_laravel_package", "recommend_laravel_packages", "get_laravel_service_info"]),
    ("Learning (experimental)", ["get_laravel_learning_path", "browse_docs_by_category"]),
]

RESOURCES = {
    "laravel://{path*}": "A framework page: `laravel://queues.md`, or `laravel://12.x/queues.md` for a named version.",
    "laravel-external://{service}/{path*}": "A page of a first-party service: `laravel-external://forge/servers/php`.",
    "laravel-package://{package}/{path*}": "A page of a fetched package: `laravel-package://livewire/quickstart.md`.",
}


def type_of(schema: Dict[str, Any]) -> str:
    """A short, readable type for a JSON Schema fragment."""
    if "anyOf" in schema:
        return " or ".join(dict.fromkeys(type_of(option) for option in schema["anyOf"] if option.get("type") != "null"))
    kind = schema.get("type", "any")
    if kind == "array":
        return f"array of {type_of(schema.get('items', {}))}"
    return str(kind)


def cell(text: Any) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def allowed(schema: Dict[str, Any]) -> str:
    values = schema.get("enum") or schema.get("items", {}).get("enum")
    if values:
        return ", ".join(f"`{value}`" for value in values if value is not None)
    if "minimum" in schema or "maximum" in schema:
        return f"{schema.get('minimum', '')} to {schema.get('maximum', '')}"
    return ""


def argument_rows(schema: Dict[str, Any]) -> List[str]:
    required = set(schema.get("required", []))
    rows = []
    for name, spec in schema.get("properties", {}).items():
        default = "required" if name in required else f"`{json.dumps(spec.get('default'))}`"
        rows.append(f"| `{name}` | {type_of(spec)} | {default} | {cell(spec.get('description', ''))} | {allowed(spec)} |")
    return rows


def field_rows(schema: Dict[str, Any], prefix: str = "") -> List[str]:
    required = set(schema.get("required", []))
    rows = []
    for name, spec in schema.get("properties", {}).items():
        path = f"{prefix}{name}"
        always = "yes" if name in required else ""
        note = cell(spec.get("description", ""))
        values = allowed(spec)
        if values:
            note = f"{note} One of {values}.".strip()
        rows.append(f"| `{path}` | {type_of(spec)} | {always} | {note} |")
        nested = spec.get("items", spec) if spec.get("type") == "array" else spec
        if nested.get("type") == "object" and nested.get("properties"):
            rows += field_rows(nested, f"{path}[]." if spec.get("type") == "array" else f"{path}.")
    return rows


async def served() -> Dict[str, Any]:
    with tempfile.TemporaryDirectory() as directory:
        server = create_mcp_server("Reference", Path(directory), "12.x", transform_mode=None)
        async with Client(server) as client:
            return {tool.name: tool for tool in await client.list_tools()}


def render() -> str:
    tools = asyncio.run(served())
    grouped = [name for _title, names in GROUPS for name in names]
    assert sorted(grouped) == sorted(tools), "GROUPS must list every served tool exactly once"

    major_minor = ".".join(__version__.split(".")[:2])
    out = [
        "# API reference",
        "",
        "<!-- Generated by scripts/generate_api_reference.py from the running server. Do not edit by hand. -->",
        "",
        f"The tools, resources and errors of Laravel MCP Companion {major_minor}, as a client sees them with",
        "`--transform-mode none`. In the default `search` mode the same tools are reached through the",
        "`search_tools` and `call_tool` meta-tools, which belong to FastMCP and are not described here.",
        "",
        "[VERSIONING.md](VERSIONING.md) says which parts of this are covered by the compatibility promise.",
        "`tests/protocol/contract.json` is the machine-readable form of the same surface.",
        "",
        "## Results",
        "",
        "Every tool returns two things: text for a model to read, and `structuredContent`, an object that",
        "satisfies the tool's output schema. The text is the same object encoded as",
        "[TOON](https://toonformat.dev), except for the two read tools, whose text is the page's markdown.",
        "",
        "A field marked *always* is present in every successful result. Other fields are present when they",
        "apply.",
        "",
        "## Errors",
        "",
        "A tool that cannot do what was asked returns a result with `isError: true` and this object as its",
        "structured content (and, TOON-encoded, as its text):",
        "",
        "```json",
        '{"error": {"code": "unknown_version", "message": "Laravel version \'99.x\' is not available", "details": {"supported_versions": ["12.x", "13.x"]}}}',
        "```",
        "",
        "`code` is what to branch on. `message` is for a person or a model. `details` is present when there",
        "is something that helps the caller recover.",
        "",
        "| Code | Meaning |",
        "|------|---------|",
        *[f"| `{code}` | {cell(meaning)} |" for code, meaning in ERROR_MEANINGS.items()],
        "",
        "Finding nothing is not an error: a search with no hits succeeds with `count: 0`.",
        "",
        "An argument the framework itself rejects, such as one the tool does not have, produces FastMCP's",
        "own validation error, which is text only.",
        "",
    ]

    for title, names in GROUPS:
        out += [f"## {title}", ""]
        for name in names:
            tool = tools[name]
            out += [f"### `{name}`", ""]
            if name in EXPERIMENTAL_TOOLS:
                out += ["*Experimental: may change in a minor release.*", ""]
            if not REGISTRY[name].read_only:
                out += ["*Writes to the documentation directory and uses the network.*", ""]
            out += [tool.description.strip(), ""]
            rows = argument_rows(tool.inputSchema)
            if rows:
                out += ["| Argument | Type | Default | Description | Allowed |", "|----------|------|---------|-------------|---------|", *rows, ""]
            else:
                out += ["Takes no arguments.", ""]
            out += ["Returns:", "", "| Field | Type | Always | Description |", "|-------|------|--------|-------------|",
                    *field_rows(tool.outputSchema), ""]

    out += [
        "## Resources",
        "",
        "Three resource templates serve the same pages the read tools do, as markdown.",
        "",
        "| Template | Serves |",
        "|----------|--------|",
        *[f"| `{template}` | {cell(description)} |" for template, description in RESOURCES.items()],
        "",
    ]
    return "\n".join(out)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != text:
            print("API.md is out of date. Run: python scripts/generate_api_reference.py", file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
